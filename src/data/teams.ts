import { LeagueId, Position, TeamDirection, TeamInfo } from '../types/game';

/**
 * 구단 고유 해시 기반 결정론적 보강 필요 포지션/전술 성향 부여 헬퍼
 */
function deriveDefaultNeeds(id: string): Position[] {
  const allPos: Position[] = ['PG', 'SG', 'SF', 'PF', 'C'];
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash * 31 + id.charCodeAt(i)) % 997;
  }
  const first = allPos[hash % 5];
  const second = allPos[(hash + 2) % 5];
  return [first, second];
}

function deriveDirection(rating: number, league: LeagueId): TeamDirection {
  const thresholdHigh = league === 'NBA' ? 88 : league === 'KBL' ? 76 : 68;
  const thresholdLow = league === 'NBA' ? 82 : league === 'KBL' ? 72 : 63;
  if (rating >= thresholdHigh) return 'CONTENDER';
  if (rating <= thresholdLow) return 'REBUILDING';
  return 'PLAYOFF_HUNT';
}


