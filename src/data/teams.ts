export function getTeamsByLeague(
  league: LeagueId,
  ratingsMap?: Record<string, number>
): TeamInfo[] {
  return ALL_TEAMS.filter((t) => t.league === league && !t.isMilitaryTeam).map(
    (t) => {
      const updatedRating = ratingsMap?.[t.id] ?? t.rating;
      return {
        ...t,
        rating: updatedRating,
        direction: deriveDirection(updatedRating, t.league),
      };
    }
  );
}

export function getTeamById(
  id: string,
  ratingsMap?: Record<string, number>
): TeamInfo {
  const found =
    ALL_TEAMS.find((t) => t.id === id) ||
    ASIAN_NATIONAL_TEAMS.find((t) => t.id === id) ||
    HIGH_SCHOOL_TEAMS[0];
  const updatedRating = ratingsMap?.[found.id] ?? found.rating;
  return {
    ...found,
    rating: updatedRating,
    direction: found.isMilitaryTeam
      ? 'PLAYOFF_HUNT'
      : deriveDirection(updatedRating, found.league),
  };
}

