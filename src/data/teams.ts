/**
 * 구단 고유 해시 기반 결정론적 보강 필요 포지션/전술 성향 부여 헬퍼
 */
function deriveDefaultNeeds(id: string): Position[] {
  const allPos: Position[] = ['PG', 'SG', 'SF', 'PF', 'C'];
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash * 31 + id.charCodeAt(i)) % 997;
  }
  const first = allPos[hash % 5];
  const second = allPos[(hash + 2) % 5];
  return [first, second];
}

const TEAM_STYLES: NonNullable<TeamInfo['preferredStyle']>[] = [
  'PACE_AND_SPACE',
  'DEFENSE_GRIT',
  'HALF_COURT',
  'BALANCED',
];

function derivePreferredStyle(id: string): NonNullable<TeamInfo['preferredStyle']> {
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash * 37 + id.charCodeAt(i)) % 991;
  }
  return TEAM_STYLES[hash % TEAM_STYLES.length];
}

