/**
 * 매 오프시즌 구단 전력 동적 변동 (현실형 세대교체 사이클)
 * - 구단의 태초 고정 레이팅이 아닌 '해당 리그 평균'을 기준으로 완만히 순환해
 *   2~4년 왕조 유지 후 자연 하락(샐러리캡·노쇠화)과 하위권 드래프트 반등이 모두 일어나도록 설계
 */
function createSeededRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function evolveLeagueTeamRatings(
  currentMap: Record<string, number>,
  sharedRng: () => number = Math.random
): Record<string, number> {
  const nextMap: Record<string, number> = { ...currentMap };
  // 1.2.0: 미국 고교 팀 전력 변동은 별도 난수로 계산합니다. 공용 난수를 쓰면 미국 고교 팀 수만큼
  // 이후 난수 흐름이 밀려, 미국 고교와 상관없는 기존 커리어 결과까지 바뀌기 때문입니다.
  const usHighSchoolRng = createSeededRng(
    US_HIGH_SCHOOL_TEAMS.reduce(
      (acc, t, i) => (acc * 31 + (currentMap[t.id] ?? t.rating) * (i + 7)) >>> 0,
      0x9e3779b9
    )
  );

  // 리그별 기준 평균 레이팅 계산 (군팀 제외)
  const leagueSum: Partial<Record<LeagueId, number>> = {};
  const leagueCnt: Partial<Record<LeagueId, number>> = {};
  for (const t of ALL_TEAMS) {
    if (t.isMilitaryTeam) continue;
    leagueSum[t.league] = (leagueSum[t.league] ?? 0) + t.rating;
    leagueCnt[t.league] = (leagueCnt[t.league] ?? 0) + 1;
  }

  for (const t of ALL_TEAMS) {
    if (t.isMilitaryTeam) {
      nextMap[t.id] = t.rating;
      continue;
    }
    const rng = t.league === 'US_HIGH_SCHOOL' ? usHighSchoolRng : sharedRng;
    const cur = currentMap[t.id] ?? t.rating;
    const leagueMean =
      (leagueSum[t.league] ?? t.rating) / Math.max(1, leagueCnt[t.league] ?? 1);
    const gapFromMean = cur - leagueMean;

    // 연도별 기본 변동 (-3 ~ +3) + 오프시즌 빅 무브(드래프트 대박·에이스 영입/이탈) 14% 확률
    let delta = Math.floor(rng() * 7) - 3;
    if (rng() < 0.14) {
      delta += rng() < 0.5 ? 2 : -2;
    }

    // 세대교체 순환 압력: 최상위 왕조(평균 +4 이상)는 노쇠화·샐러리캡 압력,
    // 하위 리빌딩 팀(평균 -3 이하)은 상위 드래프트 픽 반등 보정
    let cycleShift = 0;
    if (gapFromMean >= 6.5) {
      cycleShift = rng() < 0.72 ? -2 : -1;
    } else if (gapFromMean >= 4.0) {
      cycleShift = rng() < 0.58 ? -1 : 0;
    } else if (gapFromMean <= -5.5) {
      cycleShift = rng() < 0.72 ? 2 : 1;
    } else if (gapFromMean <= -3.0) {
      cycleShift = rng() < 0.58 ? 1 : 0;
    }

    const bounds = LEAGUE_TEAM_RATING_BOUNDS[t.league];
    const minR = bounds.minR;
    const maxR = bounds.maxR;
    nextMap[t.id] = Math.max(
      minR,
      Math.min(maxR, Math.round(cur + delta + cycleShift))
    );
  }
  return nextMap;
}

/**
 * 특정 리그 내에서 선수의 주/부포지션 수요와 구단 기조에 가장 잘 맞는 구단을 동적으로 선택합니다.
 */
export function selectBestFitTeamForPlayer(
  league: LeagueId,
  primaryPos: Position,
  secondaryPos: Position | null = null,
  ratingsMap?: Record<string, number>,
  rng: () => number = Math.random
): TeamInfo {
  const pool = getTeamsByLeague(league, ratingsMap);
  const matching = pool.filter(
    (t) =>
      t.neededPositions?.includes(primaryPos) ||
      (secondaryPos ? t.neededPositions?.includes(secondaryPos) : false)
  );
  const targetPool = matching.length > 0 ? matching : pool;
  return (
    targetPool[Math.floor(rng() * targetPool.length)] ||
    pool[0] ||
    HIGH_SCHOOL_TEAMS[0]
  );
}

