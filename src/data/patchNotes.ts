export interface PatchNoteBalanceChange {
  /** 바뀐 대상 (예: 'NBA 드래프트') */
  target: string;
  /** 체감 방향 */
  direction: 'harder' | 'easier' | 'changed';
  /** 무엇이 어떻게 달라지는지 + 이유 (수치 없이) */
  detail: string;
}

export interface PatchNote {
  version: string;
  /** 배포일 (YYYY-MM-DD) */
  date: string;
  title: string;
  /** 한 문장 요약 */
  summary: string;
  highlights: string[];
  balance?: PatchNoteBalanceChange[];
  fixes?: string[];
  /** 기존 세이브에 영향이 있을 때만 적습니다. */
  saveImpact?: string;
}

